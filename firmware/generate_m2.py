#!/usr/bin/env python3
"""Offline lossless M2 flash tables. Does not renew the frozen manifest."""
import argparse
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
from prepare_m2_manifest import build  # noqa: E402

DEST = ROOT / "firmware/src/m2_fixtures.rs"


def manifest():
    raw = (ROOT / "tools/fixtures/m2-cases/manifest.json").read_bytes()
    frozen = json.loads(raw)
    if frozen != build():
        raise ValueError("frozen manifest mismatch: stop, do not regenerate the freeze")
    return frozen, hashlib.sha256(raw).hexdigest()


def outcomes(row):
    """Canonical portable outcomes, not architecture-dependent heap expectations."""
    lines = []
    for a in row["accepted"] or []:
        o = a["selected_from"]
        lines.append(f'ACCEPT,{a["norad_id"]},{a["epoch_utc"]},{a["groups"]},{o["group"]},{o["record"]}')
    d = row["diagnostics"]
    for p in d["parse"]:
        o = p["origin"]
        lines.append(f'PARSE,{o["group"]},{o["record"]},{p["message"]}')
    for c in d["core"]:
        if c["kind"] == "invalid-record":
            o = c["origin"]
            lines.append(f'INVALID,{c["norad_id"]},{o["group"]},{o["record"]},{c["error"]}')
        else:
            lines.append(f'CONFLICT,{c["norad_id"]},{c["epoch_utc"]}')
            for o in c["origins"]:
                lines.append(f'ORIGIN,{o["group"]},{o["record"]}')
    f = d["failure"]
    lines.append(f'FAIL,{f["group"]},{f["message"]}' if f else 'FAIL,none')
    s = row["search"]
    if s:
        lines.append(f'WORK,{int(s["complete"])},{s["evaluations"]},{s["stored_passes"]},{s["earliest_candidates"]}')
        for sat in s["satellites"]:
            lines.append(f'SAT,{sat["norad_id"]},{sat["evaluations"]},{sat["passes"]},{sat["upcoming_passes"]},{sat["status"]}')
    return "\n".join(lines) + "\n"


def string(s):
    # JSON escaping is also valid Rust for these ASCII fixtures. Explicitly
    # reject non-ASCII rather than producing Rust-invalid JSON \u escapes.
    if not s.isascii():
        raise ValueError("non-ASCII fixture needs reviewed Rust string encoding")
    return json.dumps(s)


def generate():
    m, digest = manifest()
    archive = json.loads((ROOT / "tools/fixtures/m2-cases/inputs.json").read_text())
    docs = archive["documents"]
    lines = ['// @generated by firmware/generate_m2.py; do not edit or rustfmt.',
             f'pub const MANIFEST_SHA256: &str = "{digest}";',
             f'pub const MANIFEST_ID: &str = {string(m["manifest_id"])};']
    for i, d in enumerate(docs):
        raw = d["text"].encode()
        if len(raw) != d["bytes"] or hashlib.sha256(raw).hexdigest() != d["sha256"]:
            raise ValueError("document byte/hash mismatch")
        parsed = None if d["text"] == "[" else json.loads(d["text"])
        if (len(parsed) if parsed is not None else None) != d["records"]:
            raise ValueError("document record count mismatch")
        lines.append(f'static DOCUMENT_{i}: &str = {string(d["text"])};')
    lines.append('pub static CASES: [Case; 20] = [')
    for row in m["cases"]:
        c = row["case"]
        lifetime = {"flash-control": "Flash", "ram-dropped": "Dropped", "ram-retained": "Retained"}[c["lifetime"]]
        groups = []
        for g in row["groups"]:
            i = next(i for i, d in enumerate(docs) if d["key"] == g["document"])
            sources = string('tools/fixtures/catalogue-costs.tle' if g['document'] in ('historical', 'conflict', 'invalid', 'malformed') else 'tools/fixtures/m2-pool/README.md')
            groups.append(f'Group {{ name: {string(g["name"])}, key: {string(g["document"])}, sources: {sources}, text: DOCUMENT_{i} }}')
        lines.append('Case { ' + f'id: {c["id"]}, start_utc: {string(c["start_utc"])}, site: {[float(x) for x in c["site_deg_km"]]!r}, window_s: {c["window_s"]}, allowance: {c["shared_allowance"]}, lifetime: Lifetime::{lifetime}, groups: &[{", ".join(groups)}], expected: {string(outcomes(row))}' + ' },')
    lines.append('];')
    return '\n'.join(lines) + '\n'


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--check', action='store_true')
    args = p.parse_args()
    source = generate()
    if args.check:
        if DEST.read_text() != source:
            raise SystemExit('generated M2 tables differ; run firmware/generate_m2.py')
        print('M2 tables match frozen manifest and exact decoded document bytes')
    else:
        DEST.write_text(source)


if __name__ == '__main__':
    main()
